import { network } from "hardhat";
import assert from "node:assert/strict";
import { MAINNET, readPosition, verifyMainnet, openPosition, repayDebt, withdrawCollateral, revokeProvider, borrowMore, supplyCollateral } from "../../lib/mainnet.ts";
import { BrowserProvider } from "../../node_modules/ethers/lib.esm/index.js";

const { ethers, provider:forkProvider } = await network.connect("mainnetFork");
const [user, donor] = await ethers.getSigners();
console.log("Local mainnet fork, chain",Number((await ethers.provider.getNetwork()).chainId),"block",await ethers.provider.getBlockNumber());
let selected=user.address;
const browser=new BrowserProvider({request:({method,params})=>method==="eth_accounts"||method==="eth_requestAccounts"?Promise.resolve([selected]):forkProvider.request({method,params})});
const wallet=await browser.getSigner(user.address);
const progress = (message, hash, confirmed) => console.log(message, hash || "", confirmed ?? "");
await verifyMainnet(wallet);
await openPosition(wallet, "BNB", ethers.parseEther("2"), ethers.parseEther("100"), progress);
let state = await readPosition(wallet, user.address);
assert(state.collateral > 0n && state.debt >= ethers.parseEther("100"));
selected=donor.address;
await assert.rejects(()=>borrowMore(wallet,ethers.parseEther("1"),progress),/Wallet account changed/);
selected=user.address;
await repayDebt(wallet, ethers.parseEther("25"), false, progress);
state = await readPosition(wallet, user.address);
assert(state.debt < ethers.parseEther("76"));
selected=donor.address;
const donorWallet=await browser.getSigner(donor.address);
await openPosition(donorWallet, "BNB", ethers.parseEther("1"), ethers.parseEther("40"), progress);
const token = new ethers.Contract(MAINNET.loan, ["function transfer(address,uint256) returns(bool)"], donor);
await (await token.transfer(user.address, ethers.parseEther("1"))).wait();
selected=user.address;
await repayDebt(wallet, 0n, true, progress);
state = await readPosition(wallet, user.address);
assert.equal(state.debt, 0n);
assert.equal(state.shares, 0n);
await withdrawCollateral(wallet, state.collateral, progress);
await revokeProvider(wallet, progress);
state = await readPosition(wallet, user.address);
assert.equal(state.collateral, 0n);
assert.equal(state.authorized, false);
await openPosition(wallet,"slisBNB",ethers.parseEther("1"),ethers.parseEther("40"),progress);
await supplyCollateral(wallet,ethers.parseEther("0.1"),progress);
await borrowMore(wallet,ethers.parseEther("1"),progress);
state=await readPosition(wallet,user.address);
assert(state.debt>ethers.parseEther("41"));
await repayDebt(wallet,0n,true,progress);
state=await readPosition(wallet,user.address);
await withdrawCollateral(wallet,state.collateral,progress);
await revokeProvider(wallet,progress);
state=await readPosition(wallet,user.address);
assert.equal(state.debt,0n);
assert.equal(state.collateral,0n);
console.log("PASS: real deployed contracts on a local BNB mainnet fork: stake, supply, borrow, partial repay, exact full repay, withdraw, revoke. No mainnet transactions were sent.");
